export function t(keyOrText: string, lang: SupportedLanguage = 'en'): string {
  if (!keyOrText) return '';
  const currentDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  
  // 1. Direct match in selected language
  if (currentDict[keyOrText]) return currentDict[keyOrText];

  // 2. Trimmed match
  const trimmed = keyOrText.trim();
  if (currentDict[trimmed]) return currentDict[trimmed];

  // 3. Fallback to English dict
  if (TRANSLATIONS.en[keyOrText]) return TRANSLATIONS.en[keyOrText];
  if (TRANSLATIONS.en[trimmed]) return TRANSLATIONS.en[trimmed];

  // 4. Return original
  return keyOrText;
}
