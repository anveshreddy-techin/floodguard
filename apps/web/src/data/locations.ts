/**
 * Calculates geodesic distance between two points on Earth using Haversine formula
 */
export function getDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

/**
 * Finds the nearest monitored location dossier in India from given GPS coordinates
 */
export function findNearestLocation(
  lat: number,
  lon: number
): {
  location: LocationDossier;
  distanceKm: number;
} {
  let nearest = LOCATIONS[0];
  let minDistance = Infinity;

  for (const loc of LOCATIONS) {
    const d = getDistanceKm(lat, lon, loc.lat, loc.lon);
    if (d < minDistance) {
      minDistance = d;
      nearest = loc;
    }
  }

  return {
    location: nearest,
    distanceKm: Math.round(minDistance * 10) / 10,
  };
}
